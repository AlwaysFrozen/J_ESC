#!/usr/bin/env python3
"""Generate static C object dictionary metadata and unbound pointers from CSV.

No third-party dependencies. Never writes od_user.c or application variables.
"""
import argparse
import csv
from dataclasses import dataclass
from pathlib import Path
import re
import sys


TYPES = {
    "BOOLEAN": 1, "INTEGER8": 1, "INTEGER16": 2, "INTEGER32": 4,
    "INTEGER64": 8, "UNSIGNED8": 1, "UNSIGNED16": 2, "UNSIGNED32": 4,
    "UNSIGNED64": 8, "REAL32": 4, "REAL64": 8,
}
REQUIRED = {"name", "index", "subindex", "data_type", "access"}
OPTIONAL = {"description"}


@dataclass(frozen=True)
class Entry:
    name: str
    index: int
    subindex: int
    data_type: str
    access: str
    description: str


def load_entries(path):
    entries, names, addresses = [], set(), set()
    with Path(path).open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source, strict=True)
        headers = reader.fieldnames or []
        if (len(headers) != len(set(headers)) or not REQUIRED <= set(headers)
                or set(headers) - REQUIRED - OPTIONAL):
            raise ValueError("header must contain name,index,subindex,data_type,access "
                             "and optional description, without duplicate columns")
        for row in reader:
            line = reader.line_num
            name = (row.get("name") or "").strip()
            try:
                if None in row or any(value is None for value in row.values()):
                    raise ValueError("wrong number of columns")
                row = {key: value.strip() for key, value in row.items()}
                if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
                    raise ValueError("name must start with an ASCII letter and contain "
                                     "only letters, digits or underscores")
                if name in names:
                    raise ValueError("duplicate name")
                numbers = []
                for column, maximum in (("index", 0xFFFF), ("subindex", 0xFF)):
                    value = row[column]
                    if not re.fullmatch(r"0[xX][0-9a-fA-F]+", value):
                        raise ValueError(f"{column} must be hexadecimal with a 0x prefix")
                    number = int(value, 16)
                    if not 0 <= number <= maximum:
                        raise ValueError(f"{column} out of range")
                    numbers.append(number)
                index, subindex = numbers
                if (index, subindex) in addresses:
                    raise ValueError("duplicate index/subindex")
                if row["data_type"] not in TYPES:
                    raise ValueError(f"unsupported data_type: {row['data_type']}")
                if row["access"] not in {"ro", "wo", "rw"}:
                    raise ValueError("access must be ro, wo or rw")
                entries.append(Entry(name, index, subindex, row["data_type"],
                                     row["access"], row.get("description", "")))
                names.add(name)
                addresses.add((index, subindex))
            except ValueError as error:
                raise ValueError(f"line {line} ({name or '<unnamed>'}): {error}") from error
    if not entries:
        raise ValueError("CSV must contain at least one entry")
    return sorted(entries, key=lambda entry: (entry.index, entry.subindex))


def comment(text):
    # Never allow CSV documentation to end a C comment or splice source lines.
    return " ".join(text.replace("*/", "* /").replace("\\", "/").splitlines())


def render(entries):
    banner = "/* Generated by tools/generate_od.py. DO NOT EDIT. */\n"
    header = [banner, "#ifndef CANOPEN_OD_GENERATED_H\n#define CANOPEN_OD_GENERATED_H\n",
              '#include "od.h"\n\ntypedef enum {\n']
    source = [banner, '#include "od_generated.h"\n\n',
              "static const OD_Entry entries[OD_ENTRY_COUNT] = {\n"]
    for slot, entry in enumerate(entries):
        header.append(f"    OD_NAME_{entry.name} = {slot},\n")
        if entry.description:
            source.append(f"    /* {comment(entry.description)} */\n")
        source.append(f'    [OD_NAME_{entry.name}] = {{"{entry.name}", 0x{entry.index:04X}, '
                      f'0x{entry.subindex:02X}, OD_{entry.data_type}, '
                      f'OD_{entry.access.upper()}, {TYPES[entry.data_type]}}},\n')
    header += [f"    OD_ENTRY_COUNT = {len(entries)}\n}} OD_Name;\n\n",
               "extern OD_Dictionary od_dictionary;\n\n#endif\n"]
    source += ["};\n\nstatic OD_Binding bindings[OD_ENTRY_COUNT];\n\n",
               "OD_Dictionary od_dictionary = {\n",
               "    .entries = entries, .bindings = bindings,\n",
               "    .count = OD_ENTRY_COUNT, .frozen = false\n};\n"]
    return {"od_generated.h": "".join(header), "od_generated.c": "".join(source)}


def main(argv=None):
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=root / "canopen/object_dictionary.csv")
    parser.add_argument("--out-dir", type=Path, default=root / "canopen/generated")
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)
    try:
        # Validate and render everything before touching any existing output.
        outputs = render(load_entries(args.csv))
        stale = []
        for name, content in outputs.items():
            path = args.out_dir / name
            if path.exists() and path.read_text(encoding="utf-8") == content:
                continue
            stale.append(name)
            if not args.check:
                args.out_dir.mkdir(parents=True, exist_ok=True)
                temporary = path.with_suffix(path.suffix + ".tmp")
                temporary.write_text(content, encoding="utf-8", newline="\n")
                temporary.replace(path)
        if args.check and stale:
            raise ValueError("stale generated files: " + ", ".join(stale))
    except (OSError, ValueError, csv.Error) as error:
        print(f"OD generation failed: {error}", file=sys.stderr)
        return 1
    print("OD files are up to date" if args.check else "OD files generated (unchanged files preserved)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
